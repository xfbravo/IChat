package com.ichat.android.data.network

/**
 * Android 端必须和 C++/Qt 客户端、Boost.Asio 服务端保持完全一致的消息类型表。
 *
 * 新媒体消息继续走 CHAT_MESSAGE，并通过 content_type 区分 image/voice/video/file。
 * IMAGE、FILE、VOICE 只保留为兼容旧客户端的包头类型。
 */
enum class MsgType(val value: Int) {
    HEARTBEAT(0x0001),
    LOGIN(0x0002),
    REGISTER_REQ(0x0003),
    LOGOUT(0x0004),
    CHAT_MESSAGE(0x0005),
    IMAGE(0x0006),
    FILE(0x0007),
    VOICE(0x0008),
    ACK(0x0009),
    FRIEND_REQUEST(0x000A),
    GET_FRIEND_LIST(0x000B),
    GET_FRIEND_REQUESTS(0x000C),
    FRIEND_REQUEST_RSP(0x000D),
    DELETE_FRIEND(0x000E),
    GET_CHAT_HISTORY(0x000F),
    GET_OFFLINE_MESSAGES(0x0010),
    OFFLINE_MESSAGE_ACK(0x0011),
    UPDATE_FRIEND_REMARK(0x0012),
    UPDATE_AVATAR(0x0013),
    CHANGE_PASSWORD(0x0014),
    UPDATE_PROFILE(0x0015),
    GET_USER_PROFILE(0x0016),
    CREATE_MOMENT(0x0017),
    GET_MOMENTS(0x0018),
    FILE_UPLOAD_START(0x0019),
    FILE_UPLOAD_CHUNK(0x001A),
    FILE_DOWNLOAD_REQ(0x001B),
    CREATE_GROUP(0x001C),
    GET_GROUP_LIST(0x001D),
    CALL_INVITE(0x001E),
    CALL_ACCEPT(0x001F),
    CALL_REJECT(0x0020),
    CALL_CANCEL(0x0021),
    CALL_HANGUP(0x0022),
    CALL_ICE(0x0023),
    CALL_TIMEOUT(0x0024),

    LOGIN_RSP(0x8002),
    REGISTER_RSP(0x8003),
    ERROR(0x800F),
    FRIEND_LIST_RSP(0x800A),
    FRIEND_REQUEST_NEW(0x800B),
    FRIEND_LIST_UPDATE(0x800C),
    CHAT_HISTORY_RSP(0x8010),
    OFFLINE_MESSAGE(0x8011),
    UPDATE_FRIEND_REMARK_RSP(0x8012),
    UPDATE_AVATAR_RSP(0x8013),
    CHANGE_PASSWORD_RSP(0x8014),
    UPDATE_PROFILE_RSP(0x8015),
    USER_PROFILE_RSP(0x8016),
    CREATE_MOMENT_RSP(0x8017),
    MOMENTS_RSP(0x8018),
    FILE_UPLOAD_RSP(0x8019),
    FILE_DOWNLOAD_RSP(0x801A),
    FILE_DOWNLOAD_CHUNK(0x801B),
    CREATE_GROUP_RSP(0x801C),
    GROUP_LIST_RSP(0x801D),
    GROUP_LIST_UPDATE(0x801E);

    companion object {
        fun fromValue(value: Int): MsgType? = entries.firstOrNull { it.value == value }
    }
}
